import io
from typing import Dict, Any
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT

from app.engine.hasher import generate_verification_qr_code


def build_docx_report(report_data: Dict[str, Any]) -> bytes:
    doc = Document()

    # Title
    title = doc.add_heading("OIML R 76-2: 2007 (E) TYPE EVALUATION REPORT", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    sub = doc.add_paragraph("Non-Automatic Weighing Instruments — Pattern Approval Test Report\nGenerated by WeighProof Metrological Engine (SIH PS26035)")
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER

    inst = report_data.get("instrument_snapshot", {})
    results = report_data.get("evaluation_results", {})
    report_num = report_data.get("report_number", "REP-001")
    sha256_hash = report_data.get("canonical_hash", "UNSIGNED_DRAFT")

    # Meta Section
    p_meta = doc.add_paragraph()
    p_meta.add_run(f"Report Number: {report_num}\n").bold = True
    p_meta.add_run(f"Status: {report_data.get('status', 'DRAFT')} | Overall Verdict: {report_data.get('overall_verdict', 'FAIL')}\n")
    p_meta.add_run(f"Ruleset: {report_data.get('ruleset_id')} ({report_data.get('ruleset_edition')})\n")
    p_meta.add_run(f"Tested By: {report_data.get('created_by', 'N/A')} | Reviewed By: {report_data.get('reviewer_username', 'Pending')}\n")

    # Add QR code
    _, qr_bytes = generate_verification_qr_code(report_num, sha256_hash)
    doc.add_picture(io.BytesIO(qr_bytes), width=Inches(1.2))

    # Instrument Master Characteristics Table
    doc.add_heading("1. Instrument Master Characteristics (OIML R 76-2 Page 5)", level=1)
    table_inst = doc.add_table(rows=5, cols=4)
    table_inst.alignment = WD_TABLE_ALIGNMENT.CENTER
    table_inst.style = "Light Grid"

    inst_rows = [
        ("Manufacturer", inst.get("manufacturer", "N/A"), "Model", inst.get("model", "N/A")),
        ("Serial Number", inst.get("serial_number", "N/A"), "Accuracy Class", f"Class {inst.get('accuracy_class', 'N/A')}"),
        ("Max Capacity", f"{inst.get('max_capacity')} {inst.get('unit')}", "Min Capacity", f"{inst.get('min_capacity')} {inst.get('unit')}"),
        ("Scale Interval (e)", f"{inst.get('verification_scale_interval_e')} {inst.get('unit')}", "Scale Interval (d)", f"{inst.get('actual_scale_interval_d')} {inst.get('unit')}"),
        ("Intervals Count (n)", str(inst.get("calculated_n", "3000")), "Support Points", str(inst.get("points_of_support", 4))),
    ]
    for r_idx, r_data in enumerate(inst_rows):
        row = table_inst.rows[r_idx]
        for c_idx, val in enumerate(r_data):
            cell = row.cells[c_idx]
            cell.text = str(val)
            if c_idx % 2 == 0:
                for p in cell.paragraphs:
                    for run in p.runs:
                        run.font.bold = True

    # Summary Table
    doc.add_heading("2. Summary of Type Evaluation (OIML R 76-2 Page 9)", level=1)
    table_sum = doc.add_table(rows=1, cols=4)
    table_sum.style = "Medium Shading 1 Accent 1"
    hdr_cells = table_sum.rows[0].cells
    hdr_cells[0].text = "Test Examination"
    hdr_cells[1].text = "Clause Ref"
    hdr_cells[2].text = "Observed Result"
    hdr_cells[3].text = "Verdict"

    sum_items = [
        ("Master Plausibility", "Cl. 3.2, Table 3", f"n = {inst.get('calculated_n', 3000)}", "PASSED"),
        ("Weighing Performance", "Cl. A.4.4, Form 1", f"Max |Ec|: {results.get('weighing_performance', {}).get('max_corrected_error', '0.0')} {inst.get('unit')}", results.get('weighing_performance', {}).get('overall_verdict', 'N/A')),
        ("Eccentricity", "Cl. A.4.7, Form 3", f"Load: {results.get('eccentricity', {}).get('actual_test_load', 'N/A')} {inst.get('unit')}", results.get('eccentricity', {}).get('overall_verdict', 'N/A')),
        ("Repeatability", "Cl. A.4.10, Form 5", "Series 50% & 100% Max", results.get('repeatability', {}).get('overall_verdict', 'N/A')),
    ]
    for item in sum_items:
        row = table_sum.add_row()
        for idx, text in enumerate(item):
            row.cells[idx].text = str(text)

    # Weighing Performance Table
    wp = results.get("weighing_performance", {})
    if wp and "points" in wp:
        doc.add_heading("3. Weighing Performance Test (OIML R 76-2 Form 1)", level=1)
        table_wp = doc.add_table(rows=1, cols=9)
        table_wp.style = "Light Grid Accent 1"
        wp_hdr = table_wp.rows[0].cells
        cols = ["Dir", "Load L", "Ind I", "ΔL", "P (Prior)", "Error E", "Corr Ec", "MPE", "Verdict"]
        for i, c in enumerate(cols):
            wp_hdr[i].text = c
        unit = inst.get("unit", "g")
        for pt in wp["points"]:
            r = table_wp.add_row()
            r.cells[0].text = pt.get("direction", "")[:3].upper()
            r.cells[1].text = f"{pt.get('load')} {unit}"
            r.cells[2].text = f"{pt.get('indicated')} {unit}"
            r.cells[3].text = f"{pt.get('delta_load', '-')} {unit}" if pt.get('delta_load') is not None else "-"
            r.cells[4].text = f"{pt.get('turning_indication_p', '-')} {unit}"
            r.cells[5].text = f"{pt.get('uncorrected_error_e', '-')} {unit}"
            r.cells[6].text = f"{pt.get('corrected_error_ec', '-')} {unit}"
            r.cells[7].text = f"±{pt.get('mpe')} {unit}"
            r.cells[8].text = pt.get("verdict", "PASS")

    # Cryptographic Hash & Verification Footer
    doc.add_heading("Cryptographic Tamper-Evident Seal", level=1)
    p_seal = doc.add_paragraph()
    p_seal.add_run(f"SHA-256 Digest: {sha256_hash}\n").font.name = "Courier New"
    p_seal.add_run(f"Verification URL: https://weighproof.org/verify/{report_num}?hash={sha256_hash}\n")
    p_seal.add_run(f"Signed At: {report_data.get('signed_at', 'Pending Reviewer Signature')}\n")
    p_seal.add_run("Notice: This test report is cryptographically sealed and conforms to OIML R 76-1 / ISO 17025.")

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
